"""Synthesiser node.

Turns KOHA results into the final API response. The LLM writes the prose
summary and follow-up suggestions; every URL is taken from the fetched records,
never generated by the model.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field

from . import faq as faq_kb
from .llm import OllamaClient
from .planner import Plan
from .schemas import ChatResponse, FrontendResponse, Link, Meta, Source

log = logging.getLogger("library-assistant.synth")

SUMMARY_SCHEMA = {
    "type": "object",
    "properties": {
        "summary": {"type": "string"},
        "suggestions": {"type": "array", "items": {"type": "string"}},
    },
    "required": ["summary"],
}

SUMMARY_SYSTEM = """\
You are the NFSU Library assistant. You are given catalogue search results. \
Write a helpful, factual summary (1-3 sentences) in the user's language telling \
the user what was found. Do NOT invent titles, authors or links — only use the \
records provided. If no records are provided, say no matches were found and \
suggest trying different terms. Then give up to 3 short follow-up questions the \
user could ask to refine the search. Output ONLY JSON matching the schema."""

FAQ_SYSTEM = """\
You are the NFSU Library assistant. Answer the user's question about library \
services using ONLY the provided reference information. Be concise and friendly \
(2-4 sentences). If the reference information does not cover the question, say \
so and suggest contacting the library desk. Output ONLY JSON with a "summary" \
field (and an empty "suggestions" array)."""


@dataclass
class Result:
    biblio_id: int
    title: str
    author: str | None = None
    publisher: str | None = None
    year: str | None = None
    isbn: str | None = None
    url: str = ""
    total_items: int = 0
    available: int = 0
    libraries: list[str] = field(default_factory=list)
    callnumbers: list[str] = field(default_factory=list)

    def citation(self) -> str:
        bits = []
        if self.author:
            bits.append(self.author)
        if self.publisher or self.year:
            pub = ", ".join(x for x in (self.publisher, self.year) if x)
            bits.append(pub)
        if self.isbn:
            bits.append(f"ISBN {self.isbn}")
        if self.total_items:
            bits.append(
                f"{self.available} of {self.total_items} copies available"
            )
        return ". ".join(bits)

    def as_text(self, idx: int) -> str:
        line = f"{idx}. {self.title}"
        if self.author:
            line += f" — {self.author}"
        if self.year:
            line += f" ({self.year})"
        if self.total_items:
            line += f" [available: {self.available}/{self.total_items}]"
        return line


def link_from_result(r: Result, result_type: str = "catalogue_record") -> Link:
    return Link(
        title=r.title or f"Catalogue record {r.biblio_id}",
        url=r.url,
        description=r.citation(),
        type=result_type,
    )


def _catalogue_meta(total: int, showing: int, search_url: str) -> Meta:
    return Meta(
        total_results=total,
        showing=showing,
        catalogue_search_url=search_url,
        source="koha_opac",
    )


async def _summarise(
    client: OllamaClient, system: str, user: str, default: str
) -> tuple[str, list[str]]:
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]
    try:
        data = await client.chat_json(messages, SUMMARY_SCHEMA, temperature=0.2)
    except Exception as exc:
        log.warning("summary LLM failed: %s", exc)
        return default, []
    summary = (data.get("summary") or "").strip() or default
    suggestions = [s for s in (data.get("suggestions") or []) if s][:3]
    return summary, suggestions


async def synthesise_catalogue(
    client: OllamaClient,
    query: str,
    plan: Plan,
    results: list[Result],
    total: int,
    search_url: str,
) -> ChatResponse:
    if results:
        listing = "\n".join(r.as_text(i + 1) for i, r in enumerate(results))
        user = (
            f"User query: {query}\n"
            f"Search index: {plan.index}\n"
            f"Total matches in catalogue: {total}\n"
            f"Top results:\n{listing}"
        )
        default = (
            f"I found {total} matching records in the catalogue. "
            "Here are the most relevant ones."
        )
        summary, suggestions = await _summarise(client, SUMMARY_SYSTEM, user, default)
        links = [link_from_result(r) for r in results]
    else:
        alts = ", ".join(plan.alternatives) if plan.alternatives else "broader keywords"
        summary = (
            f"I couldn't find any catalogue records for \u201c{plan.search_term}\u201d. "
            f"Try different terms (for example {alts}), or open the catalogue to "
            "search manually."
        )
        suggestions = plan.alternatives or []
        links = [
            Link(
                title="Search the NFSU catalogue manually",
                url=search_url,
                description="Open the KOHA OPAC and refine your search.",
                type="catalogue_search",
            )
        ]

    return ChatResponse(
        query=query,
        intent="catalogue_search",
        summary=summary,
        links=links,
        suggestions=suggestions,
        meta=_catalogue_meta(total, len(results), search_url),
    )


async def synthesise_faq(
    client: OllamaClient, query: str, entries: list[dict]
) -> ChatResponse:
    if entries:
        context = faq_kb.as_context(entries)
        user = f"User question: {query}\n\nReference information:\n{context}"
        summary, _ = await _summarise(client, FAQ_SYSTEM, user, entries[0]["answer"])
        links = []
        seen = set()
        for e in entries:
            for link in e.get("links", []):
                if link["url"] not in seen:
                    seen.add(link["url"])
                    links.append(Link(**link, type="resource"))
    else:
        summary = (
            "I don't have that information yet. Please contact the library desk "
            "or ask me to search the catalogue."
        )
        links = [
            Link(
                title="NFSU Library",
                url="https://nfsu.ac.in",
                description="Official university site.",
                type="resource",
            )
        ]
    return ChatResponse(
        query=query,
        intent="faq",
        summary=summary,
        links=links,
        suggestions=[
            "What are the library opening hours?",
            "How do I access e-resources from home?",
        ],
        meta=Meta(source="faq_kb"),
    )


def blocked_response(query: str, reason: str) -> ChatResponse:
    return ChatResponse(
        query=query,
        intent="out_of_scope",
        summary=(
            "I can only help with library resources and services. That request "
            "looks like it tries to change my instructions, so I can't act on it. "
            "Try asking me to find a book or about library services."
        ),
        links=[],
        suggestions=[
            "Find books on forensic science",
            "What are the library opening hours?",
        ],
        meta=Meta(source="guard", blocked=True),
    )


async def synthesise_generic(
    client: OllamaClient, query: str, intent: str, guidance: str
) -> ChatResponse:
    """Handles research_help / smalltalk / out_of_scope without a tool call."""
    user = f"User message: {query}\n\nGuidance: {guidance}"
    default = (
        "I can help you find books, journals and theses in the NFSU catalogue, "
        "and answer questions about library services."
    )
    summary, suggestions = await _summarise(client, FAQ_SYSTEM, user, default)
    return ChatResponse(
        query=query,
        intent=intent,  # type: ignore[arg-type]
        summary=summary,
        links=[
            Link(
                title="Search the NFSU catalogue",
                url="https://catalog.nfsu.ac.in",
                description="Open the KOHA OPAC.",
                type="catalogue_search",
            )
        ],
        suggestions=suggestions,
        meta=Meta(source="llm"),
    )


def _https_or_none(url: str | None) -> str | None:
    """The browser extension only renders HTTPS links."""
    if url and url.startswith("https://"):
        return url
    return None


def to_frontend(resp: ChatResponse) -> FrontendResponse:
    """Map the rich response to the browser-extension contract.

    The extension renders only ``sources[].description`` (and an optional
    ``url``), so the source description is self-contained: it begins with the
    resource title.
    """
    sources: list[Source] = []
    for link in resp.links:
        desc = link.title
        if link.description:
            desc = f"{link.title} — {link.description}"
        sources.append(
            Source(
                url=_https_or_none(link.url),
                description=desc.strip(),
                title=link.title,
            )
        )
    return FrontendResponse(text_summary=resp.summary, sources=sources)
